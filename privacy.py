def get_all_privacy_settings():
    """Return a flat list of all privacy settings with their category."""
    result = []
    for cat_name, cat_data in PRIVACY_CATEGORIES.items():
        for setting in cat_data["settings"]:
            result.append({**setting, "category": cat_name, "category_icon": cat_data["icon"]})
    return result


def get_privacy_by_id(setting_id):
    """Find a privacy setting by its ID."""
    for cat_name, cat_data in PRIVACY_CATEGORIES.items():
        for setting in cat_data["settings"]:
            if setting["id"] == setting_id:
                return {**setting, "category": cat_name}
    return None
